// ステージ開始タイミング検出のための診断専用フック(フェーズ49)。
//
// 目的: 録画中のリプレイで「各ステージがロードされた瞬間」をゲームプロセス内部
// から検出し、外部(録画スクリプト)へ実時間つきで記録できるようにするための、
// 検出手段の候補を実機で洗い出す調査用コード。
//
// 2系統の観測を同時に行う:
//
//   (A) ファイルI/O観測
//       KERNEL32のCreateFileA/W・ReadFile・SetFilePointer(Ex)・CloseHandleを
//       IATフックし、「どのファイルのどのオフセットを何バイト読んだか」を
//       一定間隔で集計ログ出力する。ステージ遷移時にはステージ固有のECL/ANM/STD
//       等をth0X.datから読み込むバーストが出るはずで、これが観測できれば
//       ゲーム内部の変数を一切知らなくてもステージ境界を検出できる。
//       BGMストリーミング(thbgm.dat)のシーク位置ジャンプも同時に観測できる。
//
//   (B) メモリ差分スキャン(ステージ番号変数の探索)
//       プロセスの書き込み可能領域のシャドウコピーを保持し、一定間隔で差分を取る。
//       「値が old+1 に変化し、値域が0〜20に収まり、起動以来の変化回数が少ない」
//       バイトだけをログに出す。ステージ番号のような低頻度・単調増加のカウンタは
//       この条件をほぼ確実に満たす一方、通常のゲーム状態(座標・乱数・カウンタ類)は
//       変化回数の条件で早期に除外される。
//       1バイト単位で見るため、BYTE変数でもWORD/DWORD変数(リトルエンディアンの
//       下位バイト)でも同じ仕掛けで拾える。
//
// 環境変数:
//   STAGE_PROBE=1                    有効化(未設定なら何もしない)
//   STAGE_PROBE_IO=0/1               (A)の有効/無効。既定1
//   STAGE_PROBE_MEM=0/1              (B)の有効/無効。既定1
//   STAGE_PROBE_SCAN_MB=<int>        (B)でスキャンする合計上限MB。既定64
//   STAGE_PROBE_INTERVAL_MS=<int>    (B)のスキャン間隔ms。既定250
//   STAGE_PROBE_MAX_CHANGES=<int>    (B)でログ対象にする最大変化回数。既定12
//   STAGE_PROBE_MAX_VALUE=<int>      (B)でログ対象にする最大値。既定20
//
// 本番ビルド(build.bat)には含めない診断専用コード。

