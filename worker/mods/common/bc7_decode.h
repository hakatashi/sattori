struct Bits {
    const uint8_t *p; unsigned pos;
    unsigned get(unsigned n) {
        unsigned v = 0;
        for (unsigned i = 0; i < n; i++, pos++) v |= (unsigned)((p[pos >> 3] >> (pos & 7)) & 1) << i;
        return v;
    }
};
inline int interp(int a, int b, int w) { return ((64 - w) * a + w * b + 32) >> 6; }
inline const uint8_t *weights(unsigned bits) { return bits == 2 ? kW2 : bits == 3 ? kW3 : kW4; }

// 16バイトのブロックを4x4のRGBA8(行優先、64バイト)へ展開する。
inline void DecodeBlock(const uint8_t *block, uint8_t out[64]) {
    Bits b{block, 0};
    unsigned m = 0;
    while (m < 8 && !b.get(1)) m++;
    if (m >= 8) { memset(out, 0, 64); return; }
    const Mode &md = kModes[m];
    unsigned part = b.get(md.pb), rot = b.get(md.rb), isb = b.get(md.isb);
    int e[3][2][4];  // [subset][endpoint][channel]
    for (int c = 0; c < 3; c++)
        for (int s = 0; s < md.ns; s++)
            for (int i = 0; i < 2; i++) e[s][i][c] = b.get(md.cb);
    for (int s = 0; s < md.ns; s++)
        for (int i = 0; i < 2; i++) e[s][i][3] = md.ab ? (int)b.get(md.ab) : 255;
    unsigned cprec = md.cb, aprec = md.ab;
    if (md.epb) {
        for (int s = 0; s < md.ns; s++)
            for (int i = 0; i < 2; i++) {
                unsigned p = b.get(1);
                for (int c = 0; c < 3; c++) e[s][i][c] = (e[s][i][c] << 1) | p;
                if (md.ab) e[s][i][3] = (e[s][i][3] << 1) | p;
            }
        cprec++; if (md.ab) aprec++;
    } else if (md.spb) {
        for (int s = 0; s < md.ns; s++) {
            unsigned p = b.get(1);
            for (int i = 0; i < 2; i++) {
                for (int c = 0; c < 3; c++) e[s][i][c] = (e[s][i][c] << 1) | p;
                if (md.ab) e[s][i][3] = (e[s][i][3] << 1) | p;
            }
        }
        cprec++; if (md.ab) aprec++;
    }
    for (int s = 0; s < md.ns; s++)
        for (int i = 0; i < 2; i++) {
            for (int c = 0; c < 3; c++) { int v = e[s][i][c] << (8 - cprec); e[s][i][c] = v | (v >> cprec); }
            if (md.ab) { int v = e[s][i][3] << (8 - aprec); e[s][i][3] = v | (v >> aprec); }
        }
    uint8_t subset[16], anchor1 = 0, anchor2 = 0;
    for (int i = 0; i < 16; i++)
        subset[i] = md.ns == 1 ? 0 : md.ns == 2 ? (uint8_t)((kP2[part] >> i) & 1) : kP3[part][i];
    if (md.ns == 2) anchor1 = kA2[part];
    if (md.ns == 3) { anchor1 = kA3a[part]; anchor2 = kA3b[part]; }
    uint8_t idx1[16], idx2[16];
    for (int i = 0; i < 16; i++) {
        bool anc = i == 0 || (md.ns >= 2 && i == anchor1) || (md.ns == 3 && i == anchor2);
        idx1[i] = (uint8_t)b.get(md.ib - (anc ? 1 : 0));
    }
    if (md.ib2)
        for (int i = 0; i < 16; i++) idx2[i] = (uint8_t)b.get(md.ib2 - (i == 0 ? 1 : 0));
    const uint8_t *wc = weights(md.ib), *wa = wc;
    const uint8_t *ic = idx1, *ia = idx1;
    if (md.ib2) {
        ia = idx2; wa = weights(md.ib2);
        if (isb) { ic = idx2; ia = idx1; wc = weights(md.ib2); wa = weights(md.ib); }
    }
    for (int i = 0; i < 16; i++) {
        const int (*ep)[4] = e[subset[i]];
        int col[4];
        for (int c = 0; c < 3; c++) col[c] = interp(ep[0][c], ep[1][c], wc[ic[i]]);
        col[3] = md.ab ? interp(ep[0][3], ep[1][3], wa[ia[i]]) : 255;
        if (rot) { int t = col[3]; col[3] = col[rot - 1]; col[rot - 1] = t; }
        for (int c = 0; c < 4; c++) out[i * 4 + c] = (uint8_t)col[c];
    }
}

// 画像全体を展開する。srcPitchはブロック行あたりのバイト数、dstPitchは画素行あたりのバイト数。
inline void DecodeImage(const uint8_t *src, unsigned srcPitch, unsigned w, unsigned h, uint8_t *dst, unsigned dstPitch) {
    uint8_t px[64];
    for (unsigned by = 0; by * 4 < h; by++) {
        const uint8_t *sr = src + by * srcPitch;
        for (unsigned bx = 0; bx * 4 < w; bx++) {
            DecodeBlock(sr + bx * 16, px);
            unsigned cw = w - bx * 4 < 4 ? w - bx * 4 : 4, ch = h - by * 4 < 4 ? h - by * 4 : 4;
            for (unsigned y = 0; y < ch; y++) memcpy(dst + (by * 4 + y) * dstPitch + bx * 16, px + y * 16, cw * 4);
        }
    }
}

