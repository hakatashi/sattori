#pragma once
#include <windows.h>

// ステージ開始時刻の記録(フェーズ49)。
//
// ゲーム内の「現在のステージ番号」を保持する変数を一定間隔でポーリングし、
// 値が変化した瞬間に、外部(録画スクリプト)が動画内時刻へ変換できる形式で
// MODログに1行出力する:
//
//   StageMarker: stage=2 prev=1 frame=11363 epoch_ms=1786599865792
//
// epoch_ms はUNIXエポックからのミリ秒。録画パイプラインの`recorder/chapters.py`が
// ffmpegの`-copyts`で保持している映像の絶対開始時刻(epoch秒)との差分を取ることで、
// 動画の先頭からの秒数に変換できる。ローカル時刻の文字列ではなくepochを出すのは、
// タイムゾーン・日付跨ぎの解釈を挟まずに引き算できるようにするため。
//
// 監視対象アドレスは「exeのモジュールベース + RVA」で指定する。RVAは
// mods/common/stage_probe_hook.* の差分スキャンで実測して特定したもので、
// ゲームデータのバージョンごとに固有(fps_display_hookのkTargetRvaと同じ性質)。
// 環境変数 STAGE_MARKER_RVA (16進、例 "0x0016ba8c") で上書きできる。
//
// 想定外の値(ステージ番号としてありえない大きな値)を読んでしまうバージョン差異が
// あった場合に誤ったマーカーを出さないよう、maxStage を超える値は無視する。

namespace autoplay {

// rva: 監視するステージ番号変数のRVA。0を渡すと環境変数指定が無い限り無効。
// width: 変数のバイト幅(1 または 4)。
// stageBase: 読み取った生値に加算して「N面」の表示値にするオフセット。
//            th07は1始まりなので0、th08は0始まりなので1を指定する。
// pollIntervalMs: ポーリング間隔。
// maxStage: これを超える値(stageBase加算後)は無視する(誤検出防止)。
bool InstallStageMarkerHook(ULONG_PTR rva, int width = 4, int stageBase = 0,
                            unsigned int pollIntervalMs = 5, int maxStage = 12);

// リプレイ再生を開始する最後のEnterを押した直後に、メニュー自動操作スレッドから
// 呼ぶ。「1面の開始時刻」を得るための補助マーカーを出力する。
//
// ゲームによっては、ステージ番号変数がメニュー表示中から既に1面相当の値
// (th08では0)になっており、リプレイ開始時に「値の変化」が起きないため
// ポーリングでは1面のマーカーが取れない。実測では、最後のEnterからステージ番号
// 変数が実際に動き出すまでは35〜43ms(th07/th08)しかないため、この時刻を1面の
// 開始時刻として使って差し支えない。
//
// ステージ番号変数側で1面のマーカーが取れるゲーム(th07)ではそちらが優先され、
// この行は使われない(scripts/25側の実装)。
void LogReplayStartMarker();

// 弾幕パターン(通常弾幕・スペルカード)の開始時刻の記録(フェーズ49続き)。
//
// 東方のボス戦では、弾幕パターンごとに画面右上へ制限時間(秒)が表示され、
// パターンが切り替わるたびにその値がリセットされる。この「制限時間」を保持する
// 変数をポーリングし、**値が増加した瞬間**(=リセット)をパターン開始として
// 記録する。カウントダウン中は単調減少なので、増加は必ずリセットを意味する。
//
// th07では実測で`th07.exe+0x00095bec`がこの変数であることを確認した
// (リセット値=制限時間、次のリセット時の残り値=制限時間-経過時間が秒単位で
// 完全に整合することで裏付け済み。詳細はreports/49参照)。
//
// 出力:
//   StageMarker: pattern limit=39 prev=20 frame=5910 epoch_ms=...
//
// `limit`はそのパターンの制限時間(秒)、`prev`は直前のパターンが終了した時点の
// 残り時間(秒)。通常弾幕とスペルカードの区別、およびスペルカード名の解決は
// 未実装(limitの値だけでは判別できない)。
bool InstallPatternMarkerHook(ULONG_PTR rva, unsigned int pollIntervalMs = 5,
                              int maxLimit = 300);

// スペルカード発動中フラグ(1バイト)の監視。通常弾幕とスペルカードを区別するために使う。
// th07では実測で`th07.exe+0x005ac82b`がスペル開始時のみ0→1になることを確認した
// (通常弾幕の開始では変化しない)。
//
// 出力:
//   StageMarker: spell flag=1 frame=5910 epoch_ms=...
//
// パターン開始マーカーとの対応付け(この時刻に近いパターン開始はスペルカード、
// そうでなければ通常弾幕)は呼び出し側(scripts/25)で行う。
bool InstallSpellFlagMarkerHook(ULONG_PTR rva, unsigned int pollIntervalMs = 5);

} // namespace autoplay
